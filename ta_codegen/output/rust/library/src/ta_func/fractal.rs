    fn fractal_step_impl(sp: &mut FractalStreamState, inHigh: f64, inLow: f64, outSwingHigh: &mut i32, outSwingLow: &mut i32) {
        let mut candHigh: f64 = 0.0_f64;
        let mut candLow: f64 = 0.0_f64;
        let mut swingHigh: usize = 0_usize;
        let mut swingLow: usize = 0_usize;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.candIdx -= rebaseShift;
            sp.i -= rebaseShift;
        }
        sp.x_inHigh[(sp.today & sp.xMask) as usize] = inHigh;
        sp.x_inLow[(sp.today & sp.xMask) as usize] = inLow;
        sp.candIdx = sp.trailingIdx + sp.optInLeftBars;
        candHigh = sp.x_inHigh[(sp.candIdx & sp.xMask) as usize];
        candLow = sp.x_inLow[(sp.candIdx & sp.xMask) as usize];
        swingHigh = 100;
        swingLow = 100;
        sp.i = sp.trailingIdx;
        while sp.i < sp.candIdx {
            if sp.x_inHigh[(sp.i & sp.xMask) as usize] >= candHigh {
                swingHigh = 0;
            }
            if sp.x_inLow[(sp.i & sp.xMask) as usize] <= candLow {
                swingLow = 0;
            }
            sp.i += 1;
        }
        sp.i = sp.candIdx + 1;
        while sp.i <= sp.today {
            if sp.x_inHigh[(sp.i & sp.xMask) as usize] >= candHigh {
                swingHigh = 0;
            }
            if sp.x_inLow[(sp.i & sp.xMask) as usize] <= candLow {
                swingLow = 0;
            }
            sp.i += 1;
        }
        (*outSwingHigh) = (swingHigh) as i32;
        (*outSwingLow) = (swingLow) as i32;
        sp.trailingIdx += 1;
        sp.today += 1;
        sp.cur_outSwingHigh = (*outSwingHigh);
        sp.cur_outSwingLow = (*outSwingLow);
    }

