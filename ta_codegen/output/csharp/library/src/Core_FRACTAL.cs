      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal FractalStream( FractalStream other )
      {
         this.core = other.core;
         this.optInLeftBars = other.optInLeftBars;
         this.optInRightBars = other.optInRightBars;
         this.trailingIdx = other.trailingIdx;
         this.candIdx = other.candIdx;
         this.i = other.i;
         this.today = other.today;
         this.xMask = other.xMask;
         this.x_inHigh = new double[other.x_inHigh.Length];
         Array.Copy( other.x_inHigh, this.x_inHigh, other.x_inHigh.Length );
         this.x_inLow = new double[other.x_inLow.Length];
         Array.Copy( other.x_inLow, this.x_inLow, other.x_inLow.Length );
         this.cur_outSwingHigh = other.cur_outSwingHigh;
         this.cur_outSwingLow = other.cur_outSwingLow;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public FractalValue Update( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("FRACTAL", "update", RetCode.BadParam);
         }
         core.FractalStepImpl(this, inHigh, inLow);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new FractalValue(cur_outSwingHigh, cur_outSwingLow);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public FractalValue Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.StreamFailure("FRACTAL", "peek", RetCode.BadParam);
         FractalStream sp = this;
         double candHigh = 0.0;
         double candLow = 0.0;
         int swingHigh = 0;
         int swingLow = 0;
         int candIdx = sp.candIdx;
         int cur_outSwingHigh = 0;
         int cur_outSwingLow = 0;
         int i = sp.i;
         int today = sp.today;
         int trailingIdx = sp.trailingIdx;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         if( today >= 1073741824 ) {
            int rebaseShift = trailingIdx & ~sp.xMask;
            today -= rebaseShift;
            trailingIdx -= rebaseShift;
            candIdx -= rebaseShift;
            i -= rebaseShift;
         }
         pkSlot0 = today & sp.xMask;
         pkVal0 = inHigh;
         pkSlot1 = today & sp.xMask;
         pkVal1 = inLow;
         candIdx = trailingIdx + sp.optInLeftBars;
         candHigh = ((candIdx & sp.xMask) != pkSlot0) ? sp.x_inHigh[candIdx & sp.xMask] : pkVal0;
         candLow = ((candIdx & sp.xMask) != pkSlot1) ? sp.x_inLow[candIdx & sp.xMask] : pkVal1;
         swingHigh = 100;
         swingLow = 100;
         i = trailingIdx;
         while( i < candIdx ) {
            if( (((i & sp.xMask) != pkSlot0) ? sp.x_inHigh[i & sp.xMask] : pkVal0) >= candHigh ) {
               swingHigh = 0;
            }
            if( (((i & sp.xMask) != pkSlot1) ? sp.x_inLow[i & sp.xMask] : pkVal1) <= candLow ) {
               swingLow = 0;
            }
            i += 1;
         }
         i = candIdx + 1;
         while( i <= today ) {
            if( (((i & sp.xMask) != pkSlot0) ? sp.x_inHigh[i & sp.xMask] : pkVal0) >= candHigh ) {
               swingHigh = 0;
            }
            if( (((i & sp.xMask) != pkSlot1) ? sp.x_inLow[i & sp.xMask] : pkVal1) <= candLow ) {
               swingLow = 0;
            }
            i += 1;
         }
         cur_outSwingHigh = swingHigh;
         cur_outSwingLow = swingLow;
         return new FractalValue(cur_outSwingHigh, cur_outSwingLow);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="outSwingHigh">Receives one <c>outSwingHigh</c> value per bar committed.</param>
      /// <param name="outSwingLow">Receives one <c>outSwingLow</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, Span<int> outSwingHigh, Span<int> outSwingLow )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || outSwingHigh.Length < barCount || outSwingLow.Length < barCount || outSwingHigh.Overlaps(outSwingLow) ) throw Core.StreamFailure("FRACTAL", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("FRACTAL", "updateAndFill", RetCode.BadParam);
            }
            core.FractalStepImpl(this, inHigh[i], inLow[i]);
            outSwingHigh[i] = cur_outSwingHigh;
            outSwingLow[i] = cur_outSwingLow;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public FractalValue Value => new FractalValue(cur_outSwingHigh, cur_outSwingLow);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public FractalStream Clone()
      {
         return new FractalStream(this);
      }
   }

   internal void FractalStepImpl( FractalStream sp, double inHigh, double inLow )
   {
      double candHigh = 0.0;
      double candLow = 0.0;
      int swingHigh = 0;
      int swingLow = 0;
      if( sp.today >= 1073741824 ) {
         int rebaseShift = sp.trailingIdx & ~sp.xMask;
         sp.today -= rebaseShift;
         sp.trailingIdx -= rebaseShift;
         sp.candIdx -= rebaseShift;
         sp.i -= rebaseShift;
      }
      sp.x_inHigh[sp.today & sp.xMask] = inHigh;
      sp.x_inLow[sp.today & sp.xMask] = inLow;
      sp.candIdx = sp.trailingIdx + sp.optInLeftBars;
      candHigh = sp.x_inHigh[sp.candIdx & sp.xMask];
      candLow = sp.x_inLow[sp.candIdx & sp.xMask];
      swingHigh = 100;
      swingLow = 100;
      sp.i = sp.trailingIdx;
      while( sp.i < sp.candIdx ) {
         if( sp.x_inHigh[sp.i & sp.xMask] >= candHigh ) {
            swingHigh = 0;
         }
         if( sp.x_inLow[sp.i & sp.xMask] <= candLow ) {
            swingLow = 0;
         }
         sp.i += 1;
      }
      sp.i = sp.candIdx + 1;
      while( sp.i <= sp.today ) {
         if( sp.x_inHigh[sp.i & sp.xMask] >= candHigh ) {
            swingHigh = 0;
         }
         if( sp.x_inLow[sp.i & sp.xMask] <= candLow ) {
            swingLow = 0;
         }
         sp.i += 1;
      }
      sp.cur_outSwingHigh = swingHigh;
      sp.cur_outSwingLow = swingLow;
      sp.trailingIdx += 1;
      sp.today += 1;
   }

   private RetCode FractalOpenImpl( FractalStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInLeftBars, int optInRightBars, out int outBegIdx, out int outNBElement, Span<int> outSwingHigh, Span<int> outSwingLow, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double candHigh = 0;
      double candLow = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int today = 0;
      int candIdx = 0;
      int trailingIdx = 0;
      int i = 0;
      int swingHigh = 0;
      int swingLow = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInLeftBars == int.MinValue ) {
         optInLeftBars = 2;
      } else if( optInLeftBars < 1 || optInLeftBars > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInRightBars == int.MinValue ) {
         optInRightBars = 2;
      } else if( optInRightBars < 1 || optInRightBars > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* A bar is a swing high when its high is STRICTLY above the high of
       * every one of the optInLeftBars bars before it and of the
       * optInRightBars bars after it; the swing low is the mirror on inLow.
       * The verdict on a candidate bar can only be reached once its right
       * arm exists, so it is reported at the confirmation bar
       * candidate+optInRightBars -- that offset is what makes the function
       * causal, and it is where both oracle libraries report it too.
       *
       * A window that ties on either arm is not a pivot. Both arms use the
       * same strict comparison; the asymmetric >-left / >=-right variant some
       * charting docs describe would flag the later bar of a flat top.
       */
      lookbackTotal = optInLeftBars + optInRightBars;
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* The window is rescanned per bar (as MIN/MAX do when their cached
       * extremum leaves): a cached running extremum cannot answer this
       * question, because the candidate sits in the MIDDLE of the window and
       * a tie has to be distinguished from a strict win.
       *
       * The integer outputs can never share a real input's buffer -- different
       * element type; issue #130.
       */
      outIdx = 0;
      today = startIdx;
      trailingIdx = startIdx - lookbackTotal;
      while( today <= endIdx ) {
         candIdx = trailingIdx + optInLeftBars;
         candHigh = inHigh[candIdx];
         candLow = inLow[candIdx];
         swingHigh = 100;
         swingLow = 100;
         i = trailingIdx;
         while( i < candIdx ) {
            if( inHigh[i] >= candHigh ) {
               swingHigh = 0;
            }
            if( inLow[i] <= candLow ) {
               swingLow = 0;
            }
            i += 1;
         }
         i = candIdx + 1;
         while( i <= today ) {
            if( inHigh[i] >= candHigh ) {
               swingHigh = 0;
            }
            if( inLow[i] <= candLow ) {
               swingLow = 0;
            }
            i += 1;
         }
         outSwingHigh[outIdx * outStride] = swingHigh;
         outSwingLow[outIdx * outStride] = swingLow;
         outIdx += 1;
         trailingIdx += 1;
         today += 1;
      }
      /* Keep the outBegIdx relative to the
       * caller input before returning.
       */
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inHigh = new double[physX];
      double[] capX_inLow = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inHigh[fillJ & (physX - 1)] = inHigh[fillJ];
         capX_inLow[fillJ & (physX - 1)] = inLow[fillJ];
      }
      sp.optInLeftBars = optInLeftBars;
      sp.optInRightBars = optInRightBars;
      sp.trailingIdx = trailingIdx;
      sp.candIdx = candIdx;
      sp.i = i;
      sp.today = today;
      sp.xMask = physX - 1;
      sp.x_inHigh = capX_inHigh;
      sp.x_inLow = capX_inLow;
      sp.cur_outSwingHigh = outSwingHigh[(outNBElement - 1) * outStride];
      sp.cur_outSwingLow = outSwingLow[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* FractalOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal FractalStream FractalOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInLeftBars, int optInRightBars, out int outBegIdx, out int outNBElement, Span<int> outSwingHigh, Span<int> outSwingLow )
   {
      FractalStream sp = new FractalStream(this);
      RetCode retCode = FractalOpenImpl(sp, inHigh, inLow, startIdx, optInLeftBars, optInRightBars, out outBegIdx, out outNBElement, outSwingHigh, outSwingLow, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("FRACTAL", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind FractalOpen (composition seam). */
   internal FractalStream FractalOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInLeftBars, int optInRightBars )
   {
      FractalStream sp = new FractalStream(this);
      int[] sink_outSwingHigh = new int[1];
      int[] sink_outSwingLow = new int[1];
      RetCode retCode = FractalOpenImpl(sp, inHigh, inLow, startIdx, optInLeftBars, optInRightBars, out int outBegIdx, out int outNBElement, sink_outSwingHigh, sink_outSwingLow, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("FRACTAL", "open", retCode);
   }

   /// <summary>Open a live <c>FRACTAL</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="FractalStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>FRACTAL</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>FRACTAL_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>FractalOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInLeftBars">As in the batch call; see <see cref="FRACTAL_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInRightBars">As in the batch call; see <see cref="FRACTAL_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FRACTAL_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public FractalStream FractalOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInLeftBars, int optInRightBars )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "FRACTAL open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "FRACTAL open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("FRACTAL open: inLow is empty", nameof(inLow), RetCode.BadParam);
      RequireHistoryLength("FRACTAL", "open", "inLow", inLow.Length, inHigh.Length);
      return FractalOpenInternal(inHigh, inLow, 0, optInLeftBars, optInRightBars);
   }

   /// <summary><c>FractalOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>FRACTAL</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - FRACTAL_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="FractalStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInLeftBars">As in the batch call; see <see cref="FRACTAL_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInRightBars">As in the batch call; see <see cref="FRACTAL_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outSwingHigh">100 when the candidate bar is a strict swing high, 0 otherwise. Must hold
   /// at least <c>historyLen - FRACTAL_Lookback(...)</c> values.</param>
   /// <param name="outSwingLow">100 when the candidate bar is a strict swing low, 0 otherwise. Must hold
   /// at least <c>historyLen - FRACTAL_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FRACTAL_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public FractalStream FractalOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInLeftBars, int optInRightBars, Span<int> outSwingHigh, Span<int> outSwingLow )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "FRACTAL openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "FRACTAL openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("FRACTAL openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      int guardOutLen = OpenFillCount("FRACTAL", "openAndFill", inHigh.Length, FRACTAL_Lookback(optInLeftBars, optInRightBars));
      RequireHistoryLength("FRACTAL", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("FRACTAL", "openAndFill", "outSwingHigh", outSwingHigh.Length, guardOutLen);
      RequireFillLength("FRACTAL", "openAndFill", "outSwingLow", outSwingLow.Length, guardOutLen);
      if( outSwingHigh.Overlaps(outSwingLow) ) {
         throw StreamFailure("FRACTAL", "openAndFill", RetCode.BadParam);
      }
      return FractalOpenAndFillInternal(inHigh, inLow, 0, optInLeftBars, optInRightBars, out _, out _, outSwingHigh, outSwingLow);
   }
