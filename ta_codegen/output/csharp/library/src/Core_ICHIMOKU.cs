   /// Ichimoku Kinko Hyo, "one glance equilibrium chart": four lines built from
   /// highs and lows alone. Goichi Hosoda's reading is that a market's balance
   /// is visible without any smoothing — each line is the midpoint of a window,
   /// the mean of its highest high and its lowest low, so it marks the level at
   /// which that stretch of trading was evenly divided. The conversion line
   /// turns fastest, the base line is the reference, and the two leading spans
   /// are drawn ahead of price, where the band between them is read as support
   /// or resistance before it is reached.
   /// </summary>
   /// <remarks>
   /// <para>
   /// Formula and more info at
   /// <see href="https://ta-lib.org/functions/ichimoku">ta-lib.org/functions/ichimoku</see>.
   /// </para>
   /// <list type="bullet">
   /// <item><description>Each line is <c>TA_MIDPRICE</c> over its own period, and Span A is <c>TA_MEDPRICE</c> of the other two lines. Span A halves the two midpoints after each has been rounded, rather than averaging the four extremes, which is a different value in the last bit on about a quarter of the bars.</description></item>
   /// <item><description>The two spans are drawn <c>kijunPeriod</c> bars ahead of the bar that computed them. That is a display shift: it is reported through the display-shift call and changes nothing about the values, the lookback or the returned range. Every output is written at the bar that computed it.</description></item>
   /// <item><description>The lookback is the longest of the three periods less one. It is not the Senkou B period: nothing orders the three, so a base line longer than the second span dominates.</description></item>
   /// <item><description>The Chikou span, the close drawn backward, carries no computation and is not an output here: it is the input series with a display shift.</description></item>
   /// </list>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
   /// the library never pads with NaN. A valid range that ends before
   /// <c>IchimokuLookback</c> is a <b>success with no values</b> (<c>Count ==
   /// 0</c>), not an error.
   /// </para>
   /// <para>
   /// Every exception it throws, except the runtime's own
   /// <c>OutOfMemoryException</c>, implements <see cref="ITALibFailure"/>, which
   /// carries the <see cref="RetCode"/>.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price series.</param>
   /// <param name="inLow">Low price series.</param>
   /// <param name="optInTenkanPeriod">Period of the conversion line (default 9; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInKijunPeriod">Period of the base line, and the forward shift of the two spans (default
   /// 26; range 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSenkouBPeriod">Period of the second leading span (default 52; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outTenkanSen">Conversion line. Must hold at least <c>endIdx - max(startIdx,
   /// IchimokuLookback(...)) + 1</c> values, and never be empty: an empty span
   /// is an absent output.</param>
   /// <param name="outKijunSen">Base line. Must hold at least <c>endIdx - max(startIdx,
   /// IchimokuLookback(...)) + 1</c> values, and never be empty: an empty span
   /// is an absent output.</param>
   /// <param name="outSenkouSpanA">First leading span, drawn ahead by the base period. Must hold at least
   /// <c>endIdx - max(startIdx, IchimokuLookback(...)) + 1</c> values, and never
   /// be empty: an empty span is an absent output.</param>
   /// <param name="outSenkouSpanB">Second leading span, drawn ahead by the base period. Must hold at least
   /// <c>endIdx - max(startIdx, IchimokuLookback(...)) + 1</c> values, and never
   /// be empty: an empty span is an absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. A null array arrives as an empty span, and an empty span is an
   /// absent argument: for an input, or an output that cannot be declined, it is
   /// rejected even when the call would produce nothing.</description></item>
   /// <item><description>Two outputs overlap or are one array
   /// (<see href="https://ta-lib.org/spec/errors/#rb6">rule rB6</see>), or an
   /// output partially overlaps an input. Computing wholly in place (an output
   /// that IS an input) is allowed.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Midprice(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Medprice(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, Span{double})"/>
   /// <seealso cref="Core.Sar(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, double, double, Span{double})"/>
   /// <seealso cref="Core.Bbands(int, int, ReadOnlySpan{double}, int, double, double, MAType, Span{double}, Span{double}, Span{double})"/>
   public OutRange Ichimoku( int startIdx,
                             int endIdx,
                             ReadOnlySpan<double> inHigh,
                             ReadOnlySpan<double> inLow,
                             int optInTenkanPeriod,
                             int optInKijunPeriod,
                             int optInSenkouBPeriod,
                             Span<double> outTenkanSen,
                             Span<double> outKijunSen,
                             Span<double> outSenkouSpanA,
                             Span<double> outSenkouSpanB )
   {
      int guardStart = ClampedStart(startIdx, endIdx, IchimokuLookback(optInTenkanPeriod, optInKijunPeriod, optInSenkouBPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("ICHIMOKU", "inHigh", inHigh.Length, guardInLen);
      RequireLength("ICHIMOKU", "inLow", inLow.Length, guardInLen);
      if( guardStart >= 0 ) RequirePresent("ICHIMOKU", "outTenkanSen", outTenkanSen.Length);
      RequireLength("ICHIMOKU", "outTenkanSen", outTenkanSen.Length, guardOutLen);
      if( guardStart >= 0 ) RequirePresent("ICHIMOKU", "outKijunSen", outKijunSen.Length);
      RequireLength("ICHIMOKU", "outKijunSen", outKijunSen.Length, guardOutLen);
      if( guardStart >= 0 ) RequirePresent("ICHIMOKU", "outSenkouSpanA", outSenkouSpanA.Length);
      RequireLength("ICHIMOKU", "outSenkouSpanA", outSenkouSpanA.Length, guardOutLen);
      if( guardStart >= 0 ) RequirePresent("ICHIMOKU", "outSenkouSpanB", outSenkouSpanB.Length);
      RequireLength("ICHIMOKU", "outSenkouSpanB", outSenkouSpanB.Length, guardOutLen);
      RetCode retCode = IchimokuImpl(startIdx, endIdx, inHigh, inLow, optInTenkanPeriod, optInKijunPeriod, optInSenkouBPeriod, out int outBegIdx, out int outNBElement, outTenkanSen, outKijunSen, outSenkouSpanA, outSenkouSpanB);
      if( retCode != RetCode.Success ) {
         throw Failure("ICHIMOKU", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
