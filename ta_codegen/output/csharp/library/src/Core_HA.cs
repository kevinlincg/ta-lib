   /// </remarks>
   /// <param name="HAOpen">Heikin-Ashi open, the previous synthetic candle's midpoint.</param>
   /// <param name="HAHigh">Heikin-Ashi high, the raw high clamped up by the synthetic body.</param>
   /// <param name="HALow">Heikin-Ashi low, the raw low clamped down by the synthetic body.</param>
   /// <param name="HAClose">Heikin-Ashi close, the raw bar's average price.</param>
   public readonly record struct HaValue( double HAOpen, double HAHigh, double HALow, double HAClose );

   /// <summary>A live <c>HA</c> stream: one value per closed bar, bit-identical to
   /// <c>HA</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.HaOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class HaStream
   {
      internal Core core;
      internal double prevHAOpen;
      internal double prevHAClose;
      internal double cur_outHAOpen;
      internal double cur_outHAHigh;
      internal double cur_outHALow;
      internal double cur_outHAClose;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal HaStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Ha</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal HaStream( HaStream other )
      {
         this.core = other.core;
         this.prevHAOpen = other.prevHAOpen;
         this.prevHAClose = other.prevHAClose;
         this.cur_outHAOpen = other.cur_outHAOpen;
         this.cur_outHAHigh = other.cur_outHAHigh;
         this.cur_outHALow = other.cur_outHALow;
         this.cur_outHAClose = other.cur_outHAClose;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inOpen">This bar's open price.</param>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public HaValue Update( double inOpen, double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inOpen) || !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("HA", "update", RetCode.BadParam);
         }
         core.HaStepImpl(this, inOpen, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new HaValue(cur_outHAOpen, cur_outHAHigh, cur_outHALow, cur_outHAClose);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inOpen">This bar's open price.</param>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public HaValue Peek( double inOpen, double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inOpen) || !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("HA", "peek", RetCode.BadParam);
         HaStream sp = this;
         double haOpen = 0.0;
         double haClose = 0.0;
         double haHigh = 0.0;
         double haLow = 0.0;
         double tempOpen = 0.0;
         double tempHigh = 0.0;
         double tempLow = 0.0;
         double tempClose = 0.0;
         double cur_outHAClose = 0.0;
         double cur_outHAHigh = 0.0;
         double cur_outHALow = 0.0;
         double cur_outHAOpen = 0.0;
         tempOpen = inOpen;
         tempHigh = inHigh;
         tempLow = inLow;
         tempClose = inClose;
         haOpen = (sp.prevHAOpen + sp.prevHAClose) / 2.0;
         haClose = (tempOpen + tempHigh + tempLow + tempClose) / 4.0;
         /* An elementwise clamp of the raw bar against the two body edges, so
          * the extremes carry no state of their own.
          */
         haHigh = tempHigh;
         if( haOpen > haHigh ) {
            haHigh = haOpen;
         }
         if( haClose > haHigh ) {
            haHigh = haClose;
         }
         haLow = tempLow;
         if( haOpen < haLow ) {
            haLow = haOpen;
         }
         if( haClose < haLow ) {
            haLow = haClose;
         }
         /* Written only after this bar's four inputs are in locals above: an
          * output buffer is allowed to alias any input, and output slot k lands
          * on input bar k, which is at or behind `today`.
          */
         cur_outHAOpen = haOpen;
         cur_outHAHigh = haHigh;
         cur_outHALow = haLow;
         cur_outHAClose = haClose;
         return new HaValue(cur_outHAOpen, cur_outHAHigh, cur_outHALow, cur_outHAClose);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inOpen">Closed bars for <c>inOpen</c>, oldest first.</param>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outHAOpen">Receives one <c>outHAOpen</c> value per bar committed.</param>
      /// <param name="outHAHigh">Receives one <c>outHAHigh</c> value per bar committed.</param>
      /// <param name="outHALow">Receives one <c>outHALow</c> value per bar committed.</param>
      /// <param name="outHAClose">Receives one <c>outHAClose</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outHAOpen, Span<double> outHAHigh, Span<double> outHALow, Span<double> outHAClose )
      {
         int barCount = inOpen.Length;
         if( inHigh.Length != barCount || inLow.Length != barCount || inClose.Length != barCount || outHAOpen.Length < barCount || outHAHigh.Length < barCount || outHALow.Length < barCount || outHAClose.Length < barCount || outHAOpen.Overlaps(inOpen) || outHAOpen.Overlaps(inHigh) || outHAOpen.Overlaps(inLow) || outHAOpen.Overlaps(inClose) || outHAHigh.Overlaps(inOpen) || outHAHigh.Overlaps(inHigh) || outHAHigh.Overlaps(inLow) || outHAHigh.Overlaps(inClose) || outHALow.Overlaps(inOpen) || outHALow.Overlaps(inHigh) || outHALow.Overlaps(inLow) || outHALow.Overlaps(inClose) || outHAClose.Overlaps(inOpen) || outHAClose.Overlaps(inHigh) || outHAClose.Overlaps(inLow) || outHAClose.Overlaps(inClose) || outHAOpen.Overlaps(outHAHigh) || outHAOpen.Overlaps(outHALow) || outHAOpen.Overlaps(outHAClose) || outHAHigh.Overlaps(outHALow) || outHAHigh.Overlaps(outHAClose) || outHALow.Overlaps(outHAClose) ) throw Core.StreamFailure("HA", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inOpen[i]) || !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("HA", "updateAndFill", RetCode.BadParam);
            }
            core.HaStepImpl(this, inOpen[i], inHigh[i], inLow[i], inClose[i]);
            outHAOpen[i] = cur_outHAOpen;
            outHAHigh[i] = cur_outHAHigh;
            outHALow[i] = cur_outHALow;
            outHAClose[i] = cur_outHAClose;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public HaValue Value => new HaValue(cur_outHAOpen, cur_outHAHigh, cur_outHALow, cur_outHAClose);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public HaStream Clone()
      {
         return new HaStream(this);
      }
   }

   internal void HaStepImpl( HaStream sp, double inOpen, double inHigh, double inLow, double inClose )
   {
      double haOpen = 0.0;
      double haClose = 0.0;
      double haHigh = 0.0;
      double haLow = 0.0;
      double tempOpen = 0.0;
      double tempHigh = 0.0;
      double tempLow = 0.0;
      double tempClose = 0.0;
      tempOpen = inOpen;
      tempHigh = inHigh;
      tempLow = inLow;
      tempClose = inClose;
      haOpen = (sp.prevHAOpen + sp.prevHAClose) / 2.0;
      haClose = (tempOpen + tempHigh + tempLow + tempClose) / 4.0;
      /* An elementwise clamp of the raw bar against the two body edges, so
       * the extremes carry no state of their own.
       */
      haHigh = tempHigh;
      if( haOpen > haHigh ) {
         haHigh = haOpen;
      }
      if( haClose > haHigh ) {
         haHigh = haClose;
      }
      haLow = tempLow;
      if( haOpen < haLow ) {
         haLow = haOpen;
      }
      if( haClose < haLow ) {
         haLow = haClose;
      }
      /* Written only after this bar's four inputs are in locals above: an
       * output buffer is allowed to alias any input, and output slot k lands
       * on input bar k, which is at or behind `today`.
       */
      sp.cur_outHAOpen = haOpen;
      sp.cur_outHAHigh = haHigh;
      sp.cur_outHALow = haLow;
      sp.cur_outHAClose = haClose;
      sp.prevHAOpen = haOpen;
      sp.prevHAClose = haClose;
   }

   private RetCode HaOpenImpl( HaStream sp, ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, out int outBegIdx, out int outNBElement, Span<double> outHAOpen, Span<double> outHAHigh, Span<double> outHALow, Span<double> outHAClose, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      double haOpen = 0;
      double haClose = 0;
      double haHigh = 0;
      double haLow = 0;
      double prevHAOpen = 0;
      double prevHAClose = 0;
      double tempOpen = 0;
      double tempHigh = 0;
      double tempLow = 0;
      double tempClose = 0;
      int historyLen = inOpen.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inHigh.Length != inOpen.Length || inLow.Length != inOpen.Length || inClose.Length != inOpen.Length ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Heikin-Ashi ("average bar"): an OHLC-to-OHLC smoothing transform.
       *
       *   HA_close[i] = (open[i] + high[i] + low[i] + close[i]) / 4
       *   HA_open [0] = (open[0] + close[0]) / 2
       *   HA_open [i] = (HA_open[i-1] + HA_close[i-1]) / 2
       *   HA_high [i] = max(high[i], HA_open[i], HA_close[i])
       *   HA_low  [i] = min(low [i], HA_open[i], HA_close[i])
       *
       * Keep the four-term sum in THIS left-to-right order. It is the oracles'
       * association, and floating-point addition is not associative:
       * TA_AVGPRICE sums the same four terms as (H+L+C+O)/4 and differs from
       * HA_close in the last place on ordinary bars, so HA_close is not a
       * composed AVGPRICE call and the two must not be unified.
       *
       * Every operation is one addition or one division by an exact power of
       * two, so the transform is exact whenever its inputs are -- which is why
       * the external captures are frozen at tolerance 0 rather than a band.
       *
       * BOTH stability flags are declared, and they answer different questions.
       * `unstable_period` is the ABI knob: the open's recursion carries a factor
       * of 1/2 per bar, so a seed's influence halves every step and dies out
       * entirely within a few dozen bars -- a caller who spends them gets a
       * start-independent series (56 bars suffice on the regtest history, and
       * test_ha.c pins that). `path_dependent` declares
       * what is true at the DEFAULT of 0: the recursion re-seeds at the anchor,
       * so HA(3, 7, ...) starts its open at (open[3]+close[3])/2 rather than
       * warming up from bar 0. Without it the range-stability leg compares a
       * sub-range call against a full-range one and fails; with only it, the
       * knob that makes the two converge would not exist.
       */
      lookbackTotal = HA_Lookback();
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* The seed is carried as a VIRTUAL previous candle rather than as a
       * special first iteration: seeding the pair with the anchor bar's own
       * open and close makes the uniform recursion produce
       * (open+close)/2 at that bar, which is the published seed. One loop body
       * then serves the anchor bar and every bar after it -- and that same pair
       * is the streaming tier's initial state, so batch and stream share one
       * definition of "where the recursion starts".
       */
      today = startIdx - lookbackTotal;
      prevHAOpen = inOpen[today];
      prevHAClose = inClose[today];
      /* Warm-up: advance the recursion across the unstable-period bars without
       * emitting. Empty at the default knob of 0.
       */
      while( today < startIdx ) {
         tempOpen = inOpen[today];
         tempHigh = inHigh[today];
         tempLow = inLow[today];
         tempClose = inClose[today];
         haOpen = (prevHAOpen + prevHAClose) / 2.0;
         haClose = (tempOpen + tempHigh + tempLow + tempClose) / 4.0;
         prevHAOpen = haOpen;
         prevHAClose = haClose;
         today += 1;
      }
      outIdx = 0;
      while( today <= endIdx ) {
         tempOpen = inOpen[today];
         tempHigh = inHigh[today];
         tempLow = inLow[today];
         tempClose = inClose[today];
         haOpen = (prevHAOpen + prevHAClose) / 2.0;
         haClose = (tempOpen + tempHigh + tempLow + tempClose) / 4.0;
         /* An elementwise clamp of the raw bar against the two body edges, so
          * the extremes carry no state of their own.
          */
         haHigh = tempHigh;
         if( haOpen > haHigh ) {
            haHigh = haOpen;
         }
         if( haClose > haHigh ) {
            haHigh = haClose;
         }
         haLow = tempLow;
         if( haOpen < haLow ) {
            haLow = haOpen;
         }
         if( haClose < haLow ) {
            haLow = haClose;
         }
         /* Written only after this bar's four inputs are in locals above: an
          * output buffer is allowed to alias any input, and output slot k lands
          * on input bar k, which is at or behind `today`.
          */
         outHAOpen[outIdx * outStride] = haOpen;
         outHAHigh[outIdx * outStride] = haHigh;
         outHALow[outIdx * outStride] = haLow;
         outHAClose[outIdx * outStride] = haClose;
         outIdx += 1;
         prevHAOpen = haOpen;
         prevHAClose = haClose;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.prevHAOpen = prevHAOpen;
      sp.prevHAClose = prevHAClose;
      sp.cur_outHAOpen = outHAOpen[(outNBElement - 1) * outStride];
      sp.cur_outHAHigh = outHAHigh[(outNBElement - 1) * outStride];
      sp.cur_outHALow = outHALow[(outNBElement - 1) * outStride];
      sp.cur_outHAClose = outHAClose[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* HaOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal HaStream HaOpenAndFillInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, out int outBegIdx, out int outNBElement, Span<double> outHAOpen, Span<double> outHAHigh, Span<double> outHALow, Span<double> outHAClose )
   {
      HaStream sp = new HaStream(this);
      RetCode retCode = HaOpenImpl(sp, inOpen, inHigh, inLow, inClose, startIdx, out outBegIdx, out outNBElement, outHAOpen, outHAHigh, outHALow, outHAClose, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("HA", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind HaOpen (composition seam). */
   internal HaStream HaOpenInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx )
   {
      HaStream sp = new HaStream(this);
      double[] sink_outHAOpen = new double[1];
      double[] sink_outHAHigh = new double[1];
      double[] sink_outHALow = new double[1];
      double[] sink_outHAClose = new double[1];
      RetCode retCode = HaOpenImpl(sp, inOpen, inHigh, inLow, inClose, startIdx, out int outBegIdx, out int outNBElement, sink_outHAOpen, sink_outHAHigh, sink_outHALow, sink_outHAClose, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("HA", "open", retCode);
   }

   /// <summary>Open a live <c>HA</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="HaStream.Value"/> starts at the last history bar's
   /// value — bit-identical to what <c>HA</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>HA_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>HaOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>HA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public HaStream HaOpen( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose )
   {
      if( inOpen.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "HA open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "HA open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TaLibArgumentException("HA open: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("HA open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("HA open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("HA", "open", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("HA", "open", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("HA", "open", "inClose", inClose.Length, inOpen.Length);
      return HaOpenInternal(inOpen, inHigh, inLow, inClose, 0);
   }

   /// <summary><c>HaOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>HA</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - HA_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="HaStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="outHAOpen">Heikin-Ashi open, the previous synthetic candle's midpoint. Must hold at
   /// least <c>historyLen - HA_Lookback(...)</c> values.</param>
   /// <param name="outHAHigh">Heikin-Ashi high, the raw high clamped up by the synthetic body. Must hold
   /// at least <c>historyLen - HA_Lookback(...)</c> values.</param>
   /// <param name="outHALow">Heikin-Ashi low, the raw low clamped down by the synthetic body. Must hold
   /// at least <c>historyLen - HA_Lookback(...)</c> values.</param>
   /// <param name="outHAClose">Heikin-Ashi close, the raw bar's average price. Must hold at least
   /// <c>historyLen - HA_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>HA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public HaStream HaOpenAndFill( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outHAOpen, Span<double> outHAHigh, Span<double> outHALow, Span<double> outHAClose )
   {
      if( inOpen.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "HA openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "HA openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TaLibArgumentException("HA openAndFill: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("HA openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("HA openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("HA", "openAndFill", inOpen.Length, HA_Lookback());
      RequireHistoryLength("HA", "openAndFill", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("HA", "openAndFill", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("HA", "openAndFill", "inClose", inClose.Length, inOpen.Length);
      RequireFillLength("HA", "openAndFill", "outHAOpen", outHAOpen.Length, guardOutLen);
      RequireFillLength("HA", "openAndFill", "outHAHigh", outHAHigh.Length, guardOutLen);
      RequireFillLength("HA", "openAndFill", "outHALow", outHALow.Length, guardOutLen);
      RequireFillLength("HA", "openAndFill", "outHAClose", outHAClose.Length, guardOutLen);
      if( outHAOpen.Overlaps(inOpen) || outHAOpen.Overlaps(inHigh) || outHAOpen.Overlaps(inLow) || outHAOpen.Overlaps(inClose) || outHAHigh.Overlaps(inOpen) || outHAHigh.Overlaps(inHigh) || outHAHigh.Overlaps(inLow) || outHAHigh.Overlaps(inClose) || outHALow.Overlaps(inOpen) || outHALow.Overlaps(inHigh) || outHALow.Overlaps(inLow) || outHALow.Overlaps(inClose) || outHAClose.Overlaps(inOpen) || outHAClose.Overlaps(inHigh) || outHAClose.Overlaps(inLow) || outHAClose.Overlaps(inClose) || outHAOpen.Overlaps(outHAHigh) || outHAOpen.Overlaps(outHALow) || outHAOpen.Overlaps(outHAClose) || outHAHigh.Overlaps(outHALow) || outHAHigh.Overlaps(outHAClose) || outHALow.Overlaps(outHAClose) ) {
         throw StreamFailure("HA", "openAndFill", RetCode.BadParam);
      }
      return HaOpenAndFillInternal(inOpen, inHigh, inLow, inClose, 0, out _, out _, outHAOpen, outHAHigh, outHALow, outHAClose);
   }
